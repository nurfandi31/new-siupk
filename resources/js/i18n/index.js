const state = reactive({
    locale: FALLBACK_LOCALE,
});

function isSupported(code) {
    return locales.some((locale) => locale.code === code);
}

function detectLocale() {
    if (typeof window === 'undefined') return FALLBACK_LOCALE;

    try {
        const saved = window.localStorage.getItem(STORAGE_KEY);
        if (saved && isSupported(saved)) return saved;
    } catch (error) {
        // localStorage may be unavailable (private mode / restricted webview).
    }

    const browserLocale = (window.navigator?.language || '').toLowerCase();
    return browserLocale.startsWith('en') ? 'en' : FALLBACK_LOCALE;
}

export function initI18n() {
    setLocale(detectLocale(), false);
}

export function setLocale(code, persist = true) {
    state.locale = isSupported(code) ? code : FALLBACK_LOCALE;

    if (typeof document !== 'undefined') {
        document.documentElement.lang = state.locale;
    }

    if (persist) {
        try {
            window.localStorage.setItem(STORAGE_KEY, state.locale);
        } catch (error) {
            // Ignore persistence failures.
        }
    }
}

export function toggleLocale() {
    setLocale(state.locale === 'id' ? 'en' : 'id');
}

/**
 * Resolve a translation. Indonesian is the source locale, so unknown keys are
 * returned as-is. Params support both `:name` and `{name}` placeholders.
 */
export function t(key, params = {}) {
    if (key === null || key === undefined) return '';

    const source = String(key);
    let text = state.locale === 'en' ? en[source] : undefined;
    if (text === undefined) text = source;

    if (!params || typeof params !== 'object') return text;

    return String(text).replace(/\{(\w+)\}|:(\w+)/g, (match, braceKey, colonKey) => {
        const name = braceKey || colonKey;
        return params[name] !== undefined ? String(params[name]) : match;
    });
}

export function useI18n() {
    const locale = computed(() => state.locale);

    return {
        locale,
        locales,
        setLocale,
        toggleLocale,
        t,
    };
}

export default {
    initI18n,
    locales,
    setLocale,
    toggleLocale,
    t,
    useI18n,
};
